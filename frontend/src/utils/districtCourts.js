// Helper utilities for 3-Level State ➔ District ➔ Court Selection
export const getAllStates = () => {
  return Object.keys(INDIA_STATES_DISTRICTS_COURTS);
};

export const getDistrictsByState = (stateName) => {
  if (!stateName || !INDIA_STATES_DISTRICTS_COURTS[stateName]) {
    return [];
  }
  return Object.keys(INDIA_STATES_DISTRICTS_COURTS[stateName]);
};

export const getCourtsByDistrict = (stateName, districtName) => {
  if (!stateName || !districtName || !INDIA_STATES_DISTRICTS_COURTS[stateName]) {
    return [];
  }
  return INDIA_STATES_DISTRICTS_COURTS[stateName][districtName] || [];
};

export const findStateAndDistrictByCourt = (courtOrDistrictStr) => {
  if (!courtOrDistrictStr) return { state: "", district: "", court: "" };

  const cleanStr = courtOrDistrictStr.trim();
  let searchDistrict = cleanStr;
  let searchCourt = cleanStr;

  if (cleanStr.includes(" - ")) {
    const parts = cleanStr.split(" - ");
    searchDistrict = parts[0].trim();
    searchCourt = parts[1].trim();
  }

  for (const [state, districtsMap] of Object.entries(INDIA_STATES_DISTRICTS_COURTS)) {
    for (const [district, courtsList] of Object.entries(districtsMap)) {
      if (
        district.toLowerCase() === searchDistrict.toLowerCase() ||
        courtsList.some((c) => c.toLowerCase() === searchCourt.toLowerCase()) ||
        courtsList.some((c) => c.toLowerCase().includes(searchCourt.toLowerCase()))
      ) {
        return { state, district, court: searchCourt };
      }
    }
  }

  return { state: "Kerala", district: searchDistrict || "Ernakulam", court: searchCourt };
};

// Backward-Compatible DISTRICT_COURTS export (flattens districts across all states)
export const DISTRICT_COURTS = (() => {
  const map = {};
  for (const districtsMap of Object.values(INDIA_STATES_DISTRICTS_COURTS)) {
    for (const [district, courtsList] of Object.entries(districtsMap)) {
      map[district] = courtsList;
    }
  }
  return map;
})();
